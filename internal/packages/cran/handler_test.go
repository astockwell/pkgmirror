func TestCRAN_Upload_Anon401(t *testing.T) {
	f := newFixture(t, tenants.VisibilityPrivate)
	r, _ := f.do(t, http.MethodPut, f.base()+"/src", makeCRANTarGz(t, "Foo", "1.0.0"), false)
	if r.StatusCode != http.StatusUnauthorized {
		t.Fatalf("expected 401, got %d", r.StatusCode)
	}
}

func TestCRAN_UploadSourceAndDownload(t *testing.T) {
	f := newFixture(t, tenants.VisibilityPrivate)
	src := makeCRANTarGz(t, "Foo", "1.0.0")

	r, body := f.do(t, http.MethodPut, f.base()+"/src", src, true)
	if r.StatusCode != http.StatusCreated {
		t.Fatalf("upload: %d %s", r.StatusCode, body)
	}

	// download by exact filename
	r, got := f.do(t, http.MethodGet, f.base()+"/src/contrib/Foo_1.0.0.tar.gz", nil, true)
	if r.StatusCode != http.StatusOK {
		t.Fatalf("download: %d %s", r.StatusCode, got)
	}
	if !bytes.Equal(got, src) {
		t.Fatalf("round-trip mismatch: %d vs %d bytes", len(got), len(src))
	}

	// also reachable via the Archive route (CRAN serves historical
	// versions there; we treat the URL as an alias of the contrib path)
	r, got = f.do(t, http.MethodGet, f.base()+"/src/contrib/Archive/Foo/Foo_1.0.0.tar.gz", nil, true)
	if r.StatusCode != http.StatusOK {
		t.Fatalf("archive download: %d %s", r.StatusCode, got)
	}
	if !bytes.Equal(got, src) {
		t.Fatalf("archive round-trip mismatch")
	}
}

