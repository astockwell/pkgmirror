func TestCRAN_PACKAGESIndex_LatestPerPackage(t *testing.T) {
	f := newFixture(t, tenants.VisibilityPrivate)
	// Two versions of the same package, latest-upload-wins per
	// upload order (loadLatestEntries uses created_unix DESC). The
	// SQLite second resolution means we deliberately upload in
	// strict sequence rather than relying on the version string
	// for ordering.
	for _, v := range []string{"1.0.0", "1.1.0"} {
		if r, _ := f.do(t, http.MethodPut, f.base()+"/src", makeCRANTarGz(t, "Multi", v), true); r.StatusCode != http.StatusCreated {
			t.Fatalf("upload %s: %d", v, r.StatusCode)
		}
	}
	r, body := f.do(t, http.MethodGet, f.base()+"/src/contrib/PACKAGES", nil, true)
	if r.StatusCode != http.StatusOK {
		t.Fatalf("PACKAGES: %d", r.StatusCode)
	}
	text := string(body)
	// Index should have exactly one Multi paragraph, for 1.1.0 (the
	// newer upload).
	if strings.Count(text, "Package: Multi") != 1 {
		t.Fatalf("expected one Multi entry, got:\n%s", text)
	}
	if !strings.Contains(text, "Version: 1.1.0") {
		t.Fatalf("expected 1.1.0 to win:\n%s", text)
	}
	if strings.Contains(text, "Version: 1.0.0") {
		t.Fatalf("expected 1.0.0 to be hidden:\n%s", text)
	}
	// Both files remain downloadable directly though.
	if r, _ := f.do(t, http.MethodGet, f.base()+"/src/contrib/Multi_1.0.0.tar.gz", nil, true); r.StatusCode != http.StatusOK {
		t.Fatalf("older version should still download, got %d", r.StatusCode)
	}
}

