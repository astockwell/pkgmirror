// --- fixture helpers -------------------------------------------------------

// descriptionTemplate is a minimum CRAN DESCRIPTION. R requires
// Package + Version + License + Description + Title; everything
// else is optional. Imports / Depends are blank here, NeedsCompilation
// is the no-op default.
const descriptionTemplate = `Package: %s
Version: %s
Title: pkgmirror test package
Description: A minimal R package used by pkgmirror's CRAN tests.
License: MIT
Author: pkgmirror test <noreply@example.com>
Maintainer: pkgmirror test <noreply@example.com>
NeedsCompilation: no
`

// makeCRANTarGz builds a minimal CRAN source archive: a gzipped
// tarball with one entry, `<name>/DESCRIPTION`. R also requires a
// NAMESPACE file at the package root for `install.packages` to
// succeed; we include an empty one so the same fixture works in
// the blackbox harness.
func makeCRANTarGz(t *testing.T, name, version string) []byte {
	t.Helper()
	var buf bytes.Buffer
	gw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gw)
	desc := []byte(fmt.Sprintf(descriptionTemplate, name, version))
	if err := tw.WriteHeader(&tar.Header{Name: name + "/DESCRIPTION", Mode: 0o644, Size: int64(len(desc))}); err != nil {
		t.Fatalf("tar header: %v", err)
	}
	if _, err := tw.Write(desc); err != nil {
		t.Fatalf("tar write: %v", err)
	}
	namespace := []byte("# Generated by pkgmirror test fixture\n")
	if err := tw.WriteHeader(&tar.Header{Name: name + "/NAMESPACE", Mode: 0o644, Size: int64(len(namespace))}); err != nil {
		t.Fatalf("tar header: %v", err)
	}
	if _, err := tw.Write(namespace); err != nil {
		t.Fatalf("tar write: %v", err)
	}
	if err := tw.Close(); err != nil {
		t.Fatalf("tar close: %v", err)
	}
	if err := gw.Close(); err != nil {
		t.Fatalf("gz close: %v", err)
	}
	return buf.Bytes()
}

// --- fixture ---------------------------------------------------------------

type fixture struct {
	ts         *httptest.Server
	adminToken string
	tenant     string
}

func newFixture(t *testing.T, vis tenants.Visibility) *fixture {
	t.Helper()
	gin.SetMode(gin.TestMode)
	dir := t.TempDir()
	db, err := pkgdb.Open(filepath.Join(dir, "test.db"))
	if err != nil {
		t.Fatalf("open db: %v", err)
	}
	t.Cleanup(func() {
		_ = db.Close()
		_ = os.RemoveAll(dir) // load-bearing on macOS APFS
	})

	pkgModels := models.New(db)
	ts := tenants.New(db)
	us := users.New(db)
	tk := tokens.New(db)
	res, err := bootstrap.Ensure(context.Background(), ts, us, tk, bootstrap.Options{
		DefaultTenantName:       "default",
		DefaultTenantVisibility: vis,
	})
	if err != nil {
		t.Fatalf("bootstrap: %v", err)
	}
	blobs, _ := storage.NewLocalStorage(context.Background(), filepath.Join(dir, "blobs"))
	svc := pkgsvc.NewService(pkgModels, blobs)
	router, err := server.New(server.Deps{
		Service:   svc,
		Models:    pkgModels,
		Tenants:   ts,
		Templates: assets.Templates(),
		Authenticator: &auth.TokenAuthenticator{
			Tokens: tk, Users: us, Tenants: ts,
		},
	})
	if err != nil {
		t.Fatalf("build server: %v", err)
	}
	httpts := httptest.NewServer(router)
	t.Cleanup(httpts.Close)
	return &fixture{ts: httpts, adminToken: res.GeneratedAdminToken, tenant: res.DefaultTenant.Name}
}

func (f *fixture) do(t *testing.T, method, path string, body []byte, withAuth bool) (*http.Response, []byte) {
	t.Helper()
	var rdr io.Reader
	if body != nil {
		rdr = bytes.NewReader(body)
	}
	req, _ := http.NewRequest(method, f.ts.URL+path, rdr)
	if withAuth {
		req.Header.Set("Authorization", "Bearer "+f.adminToken)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		t.Fatalf("%s %s: %v", method, path, err)
	}
	out, _ := io.ReadAll(resp.Body)
	_ = resp.Body.Close()
	return resp, out
}

func (f *fixture) base() string { return "/api/packages/" + f.tenant + "/cran" }

