func TestCRAN_BinaryPACKAGESIsScoped(t *testing.T) {
	f := newFixture(t, tenants.VisibilityPrivate)
	// Same package uploaded as source AND as a binary for one
	// platform. The source PACKAGES should mention it; the binary
	// PACKAGES for the platform we published should too; an
	// unrelated platform's PACKAGES should 404 / be empty.
	src := makeCRANTarGz(t, "Scoped", "1.0.0")
	if r, _ := f.do(t, http.MethodPut, f.base()+"/src", src, true); r.StatusCode != http.StatusCreated {
		t.Fatalf("src upload")
	}
	if r, _ := f.do(t, http.MethodPut,
		f.base()+"/bin?platform=x86_64-pc-linux-gnu&rversion=4.4", src, true); r.StatusCode != http.StatusCreated {
		t.Fatalf("bin upload")
	}
	r, body := f.do(t, http.MethodGet,
		f.base()+"/bin/x86_64-pc-linux-gnu/contrib/4.4/PACKAGES", nil, true)
	if r.StatusCode != http.StatusOK {
		t.Fatalf("bin PACKAGES: %d %s", r.StatusCode, body)
	}
	if !strings.Contains(string(body), "Package: Scoped") {
		t.Fatalf("bin PACKAGES missing Scoped:\n%s", body)
	}
	// other-platform PACKAGES on a never-published platform: we
	// emit an empty document (no paragraphs) rather than 404, which
	// matches what `tools::write_PACKAGES()` would do on an empty
	// directory.
	r, body = f.do(t, http.MethodGet,
		f.base()+"/bin/aarch64-apple-darwin20/contrib/4.4/PACKAGES", nil, true)
	if r.StatusCode != http.StatusOK {
		t.Fatalf("other-platform PACKAGES: %d", r.StatusCode)
	}
	if strings.Contains(string(body), "Package: Scoped") {
		t.Fatalf("Scoped leaked into other-platform PACKAGES:\n%s", body)
	}
}

